"""
server/tcp_events.py — the legacy TCP event server (port 8888).

The proven core tool `core_get_send_message_code` hands the model a
Python snippet that pushes messages into the app over a plain TCP
socket:

    def send_event(message, sender="external"):
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            sock.connect(('127.0.0.1', 8888))
            payload = json.dumps({"sender": sender, "message": message})
            sock.sendall(payload.encode())

The PyQt app served that port with a QTcpServer; the headless backend
serves it with an asyncio server on the SAME loop FastAPI runs on, so
scripts generated by agents (on this machine) keep working unchanged.

Incoming payload: {"sender": "...", "message": "..."} — delivered
exactly like the PyQt version did:

    * appended to the ACTIVE session's shared history as a system-role
      message with the "[Event] " prefix,
    * broadcast to every output-stream client as a chat event,
    * ignored (but logged) when no session is active.
"""

from __future__ import annotations

import asyncio
import json
from typing import Any, Awaitable, Callable, Optional

Handler = Callable[[str, str], Any]


class TcpEventServer:
    """Accepts one-JSON-per-connection pushes on 127.0.0.1:<port>."""

    def __init__(self, handler: Handler):
        self._handler = handler
        self._server: Optional[asyncio.AbstractServer] = None
        self._port: Optional[int] = None

    async def start(self, port: int, host: str = "127.0.0.1") -> bool:
        try:
            self._server = await asyncio.start_server(
                self._handle_client, host, port)
            self._port = port
            print(f"[tcp-events] event server started on {host}:{port}")
            return True
        except Exception as exc:
            print(f"[tcp-events] failed to start on {host}:{port}: {exc}")
            return False

    async def stop(self) -> None:
        if self._server is not None:
            try:
                self._server.close()
                await self._server.wait_closed()
            except Exception:
                pass
            self._server = None

    # ------------------------------------------------------------------
    async def _handle_client(self, reader: asyncio.StreamReader,
                             writer: asyncio.StreamWriter) -> None:
        try:
            data = await asyncio.wait_for(reader.read(), timeout=10.0)
            if data:
                try:
                    payload = json.loads(data.decode("utf-8", "replace"))
                except Exception as exc:
                    await self._reply(writer, {"ok": False,
                                               "error": f"bad json: {exc}"})
                    return
                message = str(payload.get("message", "") or "")
                sender = str(payload.get("sender", "event") or "event")
                if message:
                    try:
                        self._handler(sender, message)
                        await self._reply(writer, {"ok": True})
                    except Exception as exc:
                        await self._reply(writer, {"ok": False,
                                                   "error": str(exc)})
                        return
                else:
                    await self._reply(writer, {"ok": False,
                                               "error": "empty message"})
        except asyncio.TimeoutError:
            pass
        except Exception as exc:
            print(f"[tcp-events] connection error: {exc}")
        finally:
            try:
                writer.close()
            except Exception:
                pass

    @staticmethod
    async def _reply(writer: asyncio.StreamWriter, obj: dict) -> None:
        try:
            writer.write((json.dumps(obj) + "\n").encode("utf-8"))
            await writer.drain()
        except Exception:
            pass
